// v0.42.0 (t2u/t4u/t5u Q-DATES-A): Dates sheet scrolls on REAL touch (CDP) at 412x915; slot targeting; picked pair survives reload.
const { phone } = require('./_launch.cjs');
const url = process.argv[2] || 'http://localhost:4179/sow/';
(async () => {
  const { b, ctx, p } = await phone(); p.setDefaultTimeout(5000);
  const cdp = await ctx.newCDPSession(p);
  let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
  const swipe = async (x, y0, y1) => { await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y: y0 }] }); for (let i = 1; i <= 10; i++) { await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: y0 + (y1 - y0) * i / 10 }] }); await p.waitForTimeout(16); } await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] }); await p.waitForTimeout(400); };
  const tap = async (sel) => { const r = await p.$eval(sel, (e) => { e.scrollIntoView({ block: 'center' }); const q = e.getBoundingClientRect(); return [q.left + q.width / 2, q.top + q.height / 2]; }); await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: r[0], y: r[1] }] }); await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] }); await p.waitForTimeout(250); };
  const open = async () => { await p.$eval('.sw-lean-dates', (e) => e.click()); await p.waitForSelector('.dp-sheet'); await p.waitForTimeout(400); };
  await p.goto(url, { waitUntil: 'networkidle' });
  await p.evaluate(() => { indexedDB.deleteDatabase('sow-app'); localStorage.clear(); });
  await p.goto(url + '#checklist/KGB_Eng_CW', { waitUntil: 'networkidle' }); await p.reload({ waitUntil: 'networkidle' }); await p.waitForTimeout(600);
  await open();
  const info = () => p.$eval('.dp-sheet', (s) => ({ top: s.getBoundingClientRect().top, sh: s.scrollHeight, ch: s.clientHeight, st: s.scrollTop, ta: getComputedStyle(s).touchAction }));
  const i0 = await info();
  ok(i0.ta.includes('pan-y'), `.dp-sheet touch-action is pan-y (${i0.ta})`);
  ok((await p.$eval('.dp-dial[data-dial=day]', (e) => getComputedStyle(e).touchAction)).includes('pan-y'), 'Day dial is pan-y');
  await swipe(206, i0.top + 160, i0.top + 20);
  const i1 = await info();
  ok(i1.sh <= i1.ch || i1.st > 0, `finger swipe on the sheet scrolls it (scrollTop ${i0.st}→${i1.st})`);
  const dayR = await p.$eval('.dp-dial[data-dial=day]', (e) => { const r = e.getBoundingClientRect(); return [r.left + r.width / 2, r.top + r.height / 2]; });
  await swipe(dayR[0], dayR[1] + 60, dayR[1] - 60);
  ok((await info()).st >= i1.st, 'swipe on Day column scrolls the sheet (not stuck)');
  await swipe(206, 880, 200);
  const done = await p.$eval('.dp-sheet .qo-close', (e) => { const r = e.getBoundingClientRect(); return r.bottom <= innerHeight + 1 && r.top >= 0; });
  ok(done, 'Done reachable by finger scroll');
  // Option A
  ok((await p.$$('.dp-slot')).length === 2, 'two slot cards');
  ok((await p.$$('.dp-sheet input.dp-input')).length === 1, 'one topic box');
  ok(/Date 2/.test(await p.textContent('.dp-slot.on')), 'Date 2 targeted by default');
  const pair0 = await p.$$eval('.dp-slot .d', (e) => e.map((x) => x.textContent));
  await tap('.dp-slot >> nth=0');
  ok(/Date 1/.test(await p.textContent('.dp-slot.on')) && /Editing/i.test(await p.textContent('.dp-slot.on')), 'tap Date 1 targets it (Editing)');
  ok(/Save Date 1/.test(await p.textContent('.dp-save-main')), 'primary reads Save Date 1');
  const yr = await p.$eval('.dp-year', (e) => e.value);
  const iso = await p.$eval('.dp-picker', (e) => e.dataset.iso);
  ok(iso && iso.startsWith(yr), `Year dropdown (${yr}) agrees with dial date (${iso})`);
  const wd = await p.$eval('.dp-dials [data-dial=day]', (e) => e.getAttribute('aria-valuetext'));
  const real = new Date(iso + 'T00:00:00Z').toLocaleDateString('en-GB', { weekday: 'short', timeZone: 'UTC' });
  ok(wd === real, `weekday ${wd} matches real calendar ${real}`);
  await p.focus('.dp-dials [data-dial=date]'); await p.keyboard.press('ArrowUp'); await p.waitForTimeout(100);
  await tap('.dp-save-main'); await p.waitForTimeout(300);
  const pair1 = await p.$$eval('.dp-slot .d', (e) => e.map((x) => x.textContent));
  ok(pair1[1] === pair0[1] && pair1[0] !== pair0[0], `Date 1 changed only (${pair0} → ${pair1})`);
  await p.reload({ waitUntil: 'networkidle' }); await p.waitForTimeout(700); await open();
  const pair2 = await p.$$eval('.dp-slot .d', (e) => e.map((x) => x.textContent));
  ok(pair2.join() === pair1.join(), `picked pair survives reload (${pair2})`);
  // reorder note: target Date 2, move it before Date 1
  await tap('.dp-slot >> nth=1');
  await p.focus('.dp-dials [data-dial=month]'); await p.keyboard.press('ArrowUp'); await p.waitForTimeout(100);
  ok(/will become Date 1/.test(await p.textContent('.dp-sheet')), 'reorder note shown');
  // short phone (keyboard up / small screen): the sheet must really scroll by finger
  await p.setViewportSize({ width: 412, height: 600 }); await p.waitForTimeout(300);
  await p.$eval('.dp-sheet', (e) => { e.scrollTop = 0; });
  const j0 = await info(); ok(j0.sh > j0.ch, `sheet overflows at 412x600 (${j0.sh}>${j0.ch})`);
  await swipe(206, j0.top + 150, j0.top + 10);
  const j1 = await info(); ok(j1.st > 0, `finger swipe scrolls the overflowing sheet (scrollTop ${j1.st})`);
  console.log(`RESULT ${fails} fails`); await b.close(); process.exit(fails ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(2); });
